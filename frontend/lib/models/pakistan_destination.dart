import 'package:flutter/material.dart';

enum DestinationType {
  heritage,
  mountain,
  coastal,
  cultural,
  urban,
  nature,
}

class PakistanDestination {
  const PakistanDestination({
    required this.name,
    required this.province,
    required this.type,
    required this.summary,
    required this.about,
    required this.highlights,
    required this.bestTime,
    required this.knownFor,
    required this.tripLength,
    required this.pricePerDay,
    required this.discount,
    required this.rating,
  });

  final String name;
  final String province;
  final DestinationType type;
  final String summary;
  final String about;
  final List<String> highlights;
  final String bestTime;
  final String knownFor;
  final String tripLength;
  final int pricePerDay;
  final int discount;
  final double rating;

  String get imageUrl => assetImagePath;

  String get assetImagePath {
    final fileName = _destinationAssetFiles[name] ?? '${name.toLowerCase().replaceAll(' ', '_')}.jpg';
    return 'assets/destinations/$fileName';
  }

  IconData get icon {
    switch (type) {
      case DestinationType.heritage:
        return Icons.account_balance;
      case DestinationType.mountain:
        return Icons.terrain;
      case DestinationType.coastal:
        return Icons.beach_access;
      case DestinationType.cultural:
        return Icons.palette;
      case DestinationType.urban:
        return Icons.location_city;
      case DestinationType.nature:
        return Icons.forest;
    }
  }

  String get typeLabel {
    switch (type) {
      case DestinationType.heritage:
        return 'Heritage';
      case DestinationType.mountain:
        return 'Mountain';
      case DestinationType.coastal:
        return 'Coastal';
      case DestinationType.cultural:
        return 'Cultural';
      case DestinationType.urban:
        return 'Urban';
      case DestinationType.nature:
        return 'Nature';
    }
  }
}

